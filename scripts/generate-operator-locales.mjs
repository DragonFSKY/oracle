#!/usr/bin/env node
import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { spawnSync } from "node:child_process";

const root = resolve(import.meta.dirname, "..");
const localeRoot = resolve(root, "locales/operator");
const outputs = {
  web: resolve(root, "src/relay/operatorLocale.generated.ts"),
  android: resolve(
    root,
    "apps/relay-operator-android/app/src/main/java/fun/dragonfsky/oraclerelay/OperatorLocale.generated.kt",
  ),
  windows: resolve(root, "apps/relay-operator-windows/OperatorLocale.g.cs"),
  macos: resolve(
    root,
    "apps/relay-operator-macos/Sources/OracleRelayOperator/OperatorLocale.generated.swift",
  ),
};
const locales = ["en", "zh-CN"];
const placeholder = /\{([A-Za-z][A-Za-z0-9_]*)\}/g;
const suspicious =
  /(?:-----BEGIN|(?:api[_-]?key|token|password|secret)\s*[:=]\s*[^\s{]{8,}|https?:\/\/[^\s]*(?:internal|localhost|\.local|10\.\d|192\.168\.))/i;

function placeholders(value) {
  if (
    /\{[^}]*$|\}[^{}]*$/.test(value.replace(placeholder, "")) ||
    /[{}]/.test(value.replace(placeholder, ""))
  ) {
    throw new Error(`Malformed placeholder grammar in ${JSON.stringify(value)}`);
  }
  return [...value.matchAll(placeholder)]
    .map((match) => match[1])
    .sort()
    .join(",");
}

async function load(locale) {
  const parsed = JSON.parse(await readFile(resolve(localeRoot, `${locale}.json`), "utf8"));
  if (!parsed || Array.isArray(parsed) || typeof parsed !== "object")
    throw new Error(`${locale} must be a JSON object`);
  for (const [key, value] of Object.entries(parsed)) {
    if (typeof value !== "string") throw new Error(`${locale}.${key} must be a string`);
    if (suspicious.test(value))
      throw new Error(`${locale}.${key} appears to contain secret material or a private endpoint`);
    placeholders(value);
  }
  return Object.fromEntries(Object.entries(parsed).sort(([a], [b]) => a.localeCompare(b)));
}

const catalogs = Object.fromEntries(
  await Promise.all(locales.map(async (locale) => [locale, await load(locale)])),
);
const keys = Object.keys(catalogs.en);
for (const locale of locales.slice(1)) {
  const localeKeys = Object.keys(catalogs[locale]);
  if (keys.join("\0") !== localeKeys.sort().join("\0"))
    throw new Error(`${locale} key set does not match en`);
  for (const key of keys)
    if (placeholders(catalogs.en[key]) !== placeholders(catalogs[locale][key]))
      throw new Error(`${locale}.${key} placeholder set does not match en`);
}
const json = JSON.stringify(catalogs, null, 2);
const body = `// Generated by scripts/generate-operator-locales.mjs; DO NOT EDIT.\nexport const OPERATOR_LOCALES = ${json} as const;\nexport type OperatorLanguage = "system" | "zh-CN" | "en";\nexport type OperatorResolvedLocale = "zh-CN" | "en";\nexport function resolveOperatorLocale(value: string | null | undefined, systemLocale = "en"): OperatorResolvedLocale {\n  if (value === "zh-CN" || value === "en") return value;\n  return /^zh(?:[-_]|$)/i.test(systemLocale) ? "zh-CN" : "en";\n}\nexport function operatorMessage(locale: OperatorResolvedLocale, key: keyof typeof OPERATOR_LOCALES.en, values: Record<string, string | number> = {}): string {\n  return OPERATOR_LOCALES[locale][key].replace(/\\{([A-Za-z][A-Za-z0-9_]*)\\}/g, (_, name) => String(values[name] ?? "{" + name + "}"));\n}\n`;
const android = `// Generated by scripts/generate-operator-locales.mjs; DO NOT EDIT.\npackage com.dragonfsky.oraclerelay\n\ninternal object OperatorLocale {\n    private val catalogs = """${json}"""\n    private val placeholders = Regex("\\\\{([A-Za-z][A-Za-z0-9_]*)\\\\}")\n    fun resolve(value: String?, system: String = java.util.Locale.getDefault().toLanguageTag()): String = if (value == "zh-CN" || value == "en") value else if (system.startsWith("zh", true)) "zh-CN" else "en"\n    fun t(key: String, language: String, values: Map<String, Any> = emptyMap()): String {\n        val all = org.json.JSONObject(catalogs); val catalog = all.getJSONObject(resolve(language))\n        val template = catalog.optString(key, all.getJSONObject("en").optString(key, key))\n        return placeholders.replace(template) { match -> values[match.groupValues[1]]?.toString() ?: match.value }\n    }\n}\n`;
const escapedCs = (value) =>
  value
    .replaceAll("\\", "\\\\")
    .replaceAll('"', '\\"')
    .replaceAll("\r", "\\r")
    .replaceAll("\n", "\\n");
const windows = `// Generated by scripts/generate-operator-locales.mjs; DO NOT EDIT.\nusing System.Text.Json;\nusing System.Text.RegularExpressions;\nnamespace OracleRelayOperator;\ninternal static class OperatorLocale {\n    private const string CatalogJson = "${escapedCs(json)}";\n    private static readonly Regex Placeholders = new("\\\\{([A-Za-z][A-Za-z0-9_]*)\\\\}", RegexOptions.Compiled);\n    internal static string Resolve(string? value, string? system = null) => value is "zh-CN" or "en" ? value : (system ?? System.Globalization.CultureInfo.CurrentUICulture.Name).StartsWith("zh", StringComparison.OrdinalIgnoreCase) ? "zh-CN" : "en";\n    internal static string T(string key, string language, params (string Name, object Value)[] values) { using var doc = JsonDocument.Parse(CatalogJson); var locale = Resolve(language); var template = doc.RootElement.GetProperty(locale).TryGetProperty(key, out var item) ? item.GetString()! : doc.RootElement.GetProperty("en").GetProperty(key).GetString()!; return Placeholders.Replace(template, match => { foreach (var (name, value) in values) if (name == match.Groups[1].Value) return Convert.ToString(value, System.Globalization.CultureInfo.CurrentCulture); return match.Value; }); }\n}\n`;
const swift = `// Generated by scripts/generate-operator-locales.mjs; DO NOT EDIT.\nimport Foundation\nenum OperatorLocale {\n    static let catalogs = #"""\n${json}\n"""#\n    static let placeholders = try! NSRegularExpression(pattern: #"\\{([A-Za-z][A-Za-z0-9_]*)\\}"#)\n    static func resolve(_ value: String?, system: String = Locale.current.identifier) -> String { return value == "zh-CN" || value == "en" ? value! : (system.lowercased().hasPrefix("zh") ? "zh-CN" : "en") }\n    static func t(_ key: String, _ language: String, _ values: [String: String] = [:]) -> String { guard let data = catalogs.data(using: .utf8), let all = try? JSONSerialization.jsonObject(with: data) as? [String: [String: String]] else { return key }; let template = all[resolve(language)]?[key] ?? all["en"]?[key] ?? key; let matches = placeholders.matches(in: template, range: NSRange(template.startIndex..., in: template)); var cursor = template.startIndex; var result = ""; for match in matches { guard let full = Range(match.range, in: template), let name = Range(match.range(at: 1), in: template) else { continue }; result += String(template[cursor..<full.lowerBound]); result += values[String(template[name])] ?? String(template[full]); cursor = full.upperBound }; result += String(template[cursor...]); return result }\n}\n`;
function formatTypeScript(source, filepath) {
  const result = spawnSync("pnpm", ["exec", "oxfmt", "--stdin-filepath", filepath], {
    cwd: root,
    input: source,
    encoding: "utf8",
  });
  if (result.status !== 0)
    throw new Error(result.stderr || "Could not format generated locale output");
  return result.stdout;
}

const generated = { web: formatTypeScript(body, outputs.web), android, windows, macos: swift };
const check = process.argv.includes("--check");
for (const [name, output] of Object.entries(outputs)) {
  if (check) {
    let existing = "";
    try {
      existing = await readFile(output, "utf8");
    } catch {}
    if (existing !== generated[name])
      throw new Error(
        `Operator locale generated output is stale (${name}); run pnpm run locales:operator:generate`,
      );
  } else await writeFile(output, generated[name]);
}
